export function t(language, section, key) {
  const lang = translations[language] || translations["English"];
  const sec = lang[section] || translations["English"][section] || {};
  return sec[key] || translations["English"][section]?.[key] || key;
}

export function useTranslation(language) {
  return {
    t: (section, key) => t(language, section, key),
    tNav: (key) => t(language, "nav", key),
    tCommon: (key) => t(language, "common", key),
    tDash: (key) => t(language, "dashboard", key),
    tSettings: (key) => t(language, "settings", key),
  };
}
